// Два демо-сценария тренажёра "Арена переговоров" — оба про переговоры с виртуальным
// собеседником (не про "продажу нашего продукта"): роли, скрытые интересы NPC, реальные
// последствия действий игрока.
//
// maxRounds пересчитан по итогам живого прогона на РЕАЛЬНОЙ LLM (не fallback): выяснилось,
// что прежние значения были откалиброваны под диапазон quality fallback-классификатора
// (35..95, по длине сообщения), а настоящая модель оценивает даже сильные реплики заметно
// консервативнее (обычно 60-90, редко выше) — из-за этого 3-этапный уровень с maxRounds=16
// не проходился до конца ДАЖЕ при близкой к идеальной игре (воспроизведено дважды подряд:
// уровень стабильно доходил до последнего этапа, но упирался в лимit раундов, не успевая
// набрать agreementProbability). Новые значения — из расчёта ~5 раундов на этап (закрыть
// progress совсем сильной репликой) плюс запас на накопление agreementProbability в финале.
// advanceThreshold/failThreshold не трогаем — сама проблема была именно в round budget.
import { PrismaClient } from "@prisma/client";

const prisma = new PrismaClient();

async function upsertScenario(data) {
  const existing = await prisma.scenario.findFirst({ where: { title: data.title } });
  if (existing) {
    console.log(`Сценарий "${data.title}" уже существует (id=${existing.id}), пропускаю.`);
    return;
  }
  const scenario = await prisma.scenario.create({ data });
  console.log(`Создан сценарий "${data.title}" (id=${scenario.id})`);
}

